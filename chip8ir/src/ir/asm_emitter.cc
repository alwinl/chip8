namespace
{
	struct EmitContext {
		std::ostream& os;
		const IRBundle& bundle;
		asm_emitter::OutputMode mode;
	};

	class StreamStateGuard
	{
	public:
		explicit StreamStateGuard(std::ostream& os) : os(os), flags(os.flags()), fill(os.fill()) {}
		StreamStateGuard( const StreamStateGuard & /* */) = delete;
		StreamStateGuard& operator=(const StreamStateGuard&) = delete;
		StreamStateGuard(StreamStateGuard&&) = delete;
		StreamStateGuard& operator=(StreamStateGuard&&) = delete;

		~StreamStateGuard() {
			os.flags(flags);
			os.fill(fill);
		}

	private:
		std::ostream& os;
		std::ios::fmtflags flags;
		char fill;
	};

	void emit_address( std::ostream& os, uint16_t address )
	{
		os << "0x" << std::hex << std::uppercase << std::setw(3) << std::setfill('0') << address << "  ";
	}

	void emit_header( std::ostream& os, uint16_t origin, std::string name )
	{
		os << "; Disasembly of " << name << "\n";
		os << "; Generated by chidisas8\n";
		os << ";\n\n";
		os << "\t.ORG ";

		emit_address( os, origin );

		os << "\n\n";
	}

	void emit_opcode( std::ostream& os, uint16_t opcode )
	{
		const uint8_t high_byte = static_cast<unsigned>((opcode >> 8 ) & 0xFF);
		const uint8_t low_byte  = static_cast<unsigned>((opcode >> 0 ) & 0xFF);

		os << std::hex << std::uppercase
			<< std::right << std::setw(2) << std::setfill('0') << +high_byte << " ";

		os << std::hex << std::uppercase
			<< std::right << std::setw(2) << std::setfill('0') << +low_byte << "  ";
	}

	void emit_label( std::ostream& os, std::string label )
	{
		if( !label.empty() )
			label += ":";

		os << std::left << std::setw(8) << std::setfill(' ') << label;
	}

	void emit_mnemonic( std::ostream& os, const Opcode& opcode )
	{
		static std::array<std::string, opcode_count> mnemonics = {
			"NOP", "CLS", "RET", "JP", "CALL", "SE",
			"SNE", "SE", "LD", "ADD", "LD", "OR", "AND",
			"XOR", "ADD", "SUB", "SHR", "SUBN", "SHL", "SNE", "LD I,",
			"JP V0,", "RND", "DRW", "SKP", "SKNP", "LD DT,",
			"LD ST,", "ST K,", "ST DT,", "ADD I,",
			"LD F,", "LD B,", "ST [I],", "LD [I],"
		};

		os << mnemonics[ static_cast<int>(opcode) ];
	}

	void emit_operand( std::ostream& os, const Operand& opr, ILabelResolver* resolver )
	{
		std::visit( [&](auto&& operand)
		{
			const StreamStateGuard guard(os);

			using T = std::decay_t<decltype(operand)>;

			if constexpr( std::is_same_v<T, Reg> )
				os << "V" << std::uppercase << std::hex << +operand.get_index();

			else if constexpr( std::is_same_v<T, Addr> ) {
				const std::string target = resolver->get_label( operand.get_value() );
				if( target.empty() )
					os << "0x" << std::uppercase << std::hex << std::setw(3) << std::setfill('0') << +operand.get_value();
				else
					os << target;
			}

			else if constexpr( std::is_same_v<T, Imm> )
				os << "#" << std::dec << +operand.get_value();

			else if constexpr( std::is_same_v<T, Nibble> )
				os << "0x" << std::uppercase << std::hex << +operand.get_value();

		}, opr);
	}

	void emit_instruction( std::ostream& os, const IRInstruction& element, asm_emitter::OutputMode mode, ILabelResolver* resolver )
	{
		const Instruction& instruction = element.instruction;

		if( mode == asm_emitter::OutputMode::Listing ) {
			emit_address( os, element.address );
			emit_opcode( os, instruction.to_binary() );
		}

		const std::string label = resolver->get_label( element.address );

		emit_label( os, label );

		emit_mnemonic( os, instruction.opcode() );

		for( bool first = true; const auto& operand : instruction.operands() )
		{
			os << (first ? " " : ", " );
			first = false;

			emit_operand( os, operand, resolver );
		}

		os << "\n";
	}

	void emit_datablock( std::ostream& os, const IRDataBlock& element, asm_emitter::OutputMode mode, ILabelResolver* resolver )
	{
		if( mode == asm_emitter::OutputMode::Listing )
			emit_address( os, element.address );

		std::string label = resolver->get_label( element.address );
		emit_label( os, label );

		os << ".DB";

		for( bool first = true; const auto& byte : element.bytes )
		{
			os << (first ? " " : ", " );
			first = false;

			os << std::hex << "0x" << std::setw(2) << std::setfill('0') << std::uppercase << +byte;
		}

		os << " ; ";
		for( const auto& byte : element.bytes)
			os << ((byte >= 0x20 && byte <= 0x7E) ? static_cast<char>( byte ) : '.' );

		os << "\n";
	}

} // namespace
namespace asm_emitter
{
	void emit( std::ostream& os, const IRBundle& bundle, std::string bin_name, OutputMode mode )
	{
		auto * resolver = bundle.resolver.get();

		emit_header( os, bundle.ir.origin, bundle.program_name );

		for( const auto& element : bundle.ir.elements ) {

			std::visit( [&]( const auto& element ) {

				using T = std::decay_t<decltype(element)>;

				if constexpr( std::is_same_v<T, IRInstruction> ) {
					emit_instruction( os, element, mode, resolver );

				}
				else if constexpr( std::is_same_v<T, IRDataBlock> ) {
					emit_datablock( os, element, mode, resolver );

				}
				else
					static_assert( std::is_same_v<T, void>, "Unhandled IRElement type" );

				// emit_element( ctx, element );

			}, element );

		}
	}
} // namespace asm_emitter
